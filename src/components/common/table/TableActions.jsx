export default function TableActions({ actions = [] }) {
  return (
    <div
      className="flex items-center justify-center gap-2"
      onClick={(e) => e.stopPropagation()}
    >
      {actions.map((action, index) => {
        const isDisabled = Boolean(action.disabled);
        const actionKey =
          typeof action.label === "string"
            ? `${action.label}-${index}`
            : action.key || index;
        return (
          <React.Fragment key={actionKey}>
            {index > 0 && (
              <span className="text-slate-200">|</span>
            )}

            <button
              type="button"
              onClick={isDisabled ? undefined : action.onClick}
              disabled={isDisabled}
              title={action.title || action.label}
              className={`inline-flex items-center gap-1 text-xs font-medium transition-colors ${
                isDisabled
                  ? "text-slate-300 cursor-not-allowed opacity-60"
                  : action.className ?? "text-blue-600 hover:text-blue-800 cursor-pointer"
              }`}
            >
              {action.icon && (typeof action.icon === "string" ? icons[action.icon] : action.icon)}
              {action.label && <span>{action.label}</span>}
            </button>
          </React.Fragment>
        );
      })}
    </div>
  );
}
